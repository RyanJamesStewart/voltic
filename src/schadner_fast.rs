/// Degree of the bivariate Chebyshev seed (= 12). Public for the
/// [`crate::otm_context`] API.
pub const SEED_DEG_PUB: usize = SEED_DEG;
/// Lower premium-ratio bound of the seed domain. Public for context-prelude.
pub const SEED_P_LO_PUB: f64 = SEED_P_LO;
/// Upper premium-ratio bound of the seed domain. Public for context-prelude.
pub const SEED_P_HI_PUB: f64 = SEED_P_HI;

/// Below this `|k| = |ln(K/F)|` the option is treated as at-the-forward and
/// the formula collapses to the probit (`σ = 2·Φ⁻¹((c+1)/2)/√T`). Below the
/// Chebyshev seed domain (`SEED_K_LO = 0.005`), so any `k < SEED_K_LO` would
/// land us extrapolating; the probit answer is accurate enough at this scale.
const K_PROBIT_THRESHOLD: f64 = 1e-4;

/// Number of Halley iterations after the Chebyshev seed. Swept by the
/// conductor; the public-API NaN contract is preserved by the `implied_vol_fast`
/// wrapper in `crate::lib`, which falls back to the rational kernel on any
/// poisoned lane.
const HALLEY_STEPS: usize = 0;

/// Number of Householder-3 (order-4) iterations after the Halley iterations.
/// A2 sweep: pure Householder, hybrid (1 Halley + 1 HH3), etc.
const HOUSEHOLDER3_STEPS: usize = 3;

/// Vega-scaled acceptance tolerance — accept a lane iff
/// `|price(σ) − price| / vega(σ) < SIGMA_TOL` (i.e. the residual, mapped from
/// price-space into σ-space by the local linearization `dp = vega · dσ`,
/// is below tolerance). σ-direct gate; works in every regime including ATM
/// where the IG residual `G(v)` suffers catastrophic cancellation.
const SIGMA_TOL: f64 = 1e-7;

/// IG(μ, λ=1) CDF, density, and density derivative at `x > 0`, lane-packed.
///
/// **Avenue 1 (cancellation-free)**. The naive form
/// `S = Φ(−a+b) − e^(2/μ)·Φ(−a−b)` loses digits as `μ → ∞` (ATM):
/// both `Φ`-terms approach the same value and `e^(2/μ) → 1`. The identity
///
/// ```text
///   S(x; μ) = ½ · e^(−u²) · [erfcx(u) − erfcx(v)]
/// ```
///
/// with `u = (a−b)/√2`, `v = (a+b)/√2`, is mathematically the same but is
/// FP-stable everywhere: `erfcx` is slowly varying and monotone, so the
/// difference is honest. Derivation: `Φ(−z) = ½ · e^(−z²/2) · erfcx(z/√2)`
/// for `z ≥ 0`; then `v² − u² = 2ab = 2/μ` exactly cancels the `e^(2/μ)`
/// in the original.
///
/// `u` is signed; `v ≥ 0` always. Negative `u` lanes use the reflection
/// `erfcx(−y) = 2·e^(y²) − erfcx(y)`.
/// See module docs for the `f'_IG` derivation.
#[inline]
fn ig_cdf_pdf_dpdf(x: V, mu: V) -> (V, V, V) {
    let sqrt_x = x.sqrt();
    let inv_sqrt_x = V::splat(1.0) / sqrt_x;
    let a = sqrt_x / mu;

    // Cancellation-free survival: S = ½·e^(−u²)·[erfcx(u) − erfcx(v)].
    let frac_1_sqrt_2 = V::splat(core::f64::consts::FRAC_1_SQRT_2);
    let u = (a - inv_sqrt_x) * frac_1_sqrt_2;
    let v = (a + inv_sqrt_x) * frac_1_sqrt_2;

    // Research D fused form (F3 + B1 + reciprocal) saves one exp + one mul
    // per CDF vs the explicit reflect-then-prefactor sequence; see
    // `norm::ig_surv_from_uv` for the analytic collapse.
    let surv = norm::ig_surv_from_uv(u, v);
    let cdf = V::splat(1.0) - surv;

    let two_pi = V::splat(2.0 * core::f64::consts::PI);
    let inv_norm = (two_pi * x * x * x).sqrt();
    let dx = x - mu;
    let pdf = norm::vexp(-(dx * dx) / (V::splat(2.0) * mu * mu * x)) / inv_norm;

    let two = V::splat(2.0);
    let three_halves = V::splat(1.5);
    let factor = V::splat(1.0) / (two * x * x) - three_halves / x - V::splat(1.0) / (two * mu * mu);
    let dpdf = pdf * factor;
    (cdf, pdf, dpdf)
}

/// One Halley step on `G(v) = F_IG(4/v²; μ, 1) − q`, lane-packed.
#[inline]
fn halley_step(v: V, mu: V, q: V) -> V {
    let x = V::splat(4.0) / (v * v);
    let (cdf, pdf, dpdf) = ig_cdf_pdf_dpdf(x, mu);
    let g = cdf - q;
    let v2 = v * v;
    let v3 = v2 * v;
    let v4 = v2 * v2;
    let v6 = v3 * v3;
    let gp = -V::splat(8.0) * pdf / v3;
    let gpp = V::splat(64.0) * dpdf / v6 + V::splat(24.0) * pdf / v4;
    let num = V::splat(2.0) * g * gp;
    let den = V::splat(2.0) * gp * gp - g * gpp;
    let den_safe = den.abs().simd_max(V::splat(1e-300));
    let signed_den = den.is_sign_negative().select(-den_safe, den_safe);
    v - num / signed_den
}

/// One Householder-3 step (convergence order 4) on `G(v) = F_IG(4/v²; μ, 1) − q`,
/// lane-packed. Uses the corrected derivative chain (see module docs):
///   L(x)  = 1/(2x²) − 3/(2x) − 1/(2μ²)
///   L'(x) = −1/x³ + 3/(2x²)
///   f'_IG  = f_IG · L
///   f''_IG = f_IG · (L² + L')
/// G', G'', G''' derived by chain rule from `x = 4/v²`.
/// Householder-3 step: Δv = (6·G·G'² − 3·G²·G'') / (6·G'³ − 6·G·G'·G'' + G²·G''').
///
/// **A5**: also re-exported as [`householder3_step_simd`] (same function, public
/// alias) so the [`crate::otm_context`] split-API path can drive iterations
/// without re-implementing the chain.
#[inline]
fn householder3_step(v: V, mu: V, q: V) -> V {
    let x = V::splat(4.0) / (v * v);
    let (cdf, pdf, _dpdf) = ig_cdf_pdf_dpdf(x, mu);

    // L(x) and L'(x). Recomputed here (rather than threaded out of
    // `ig_cdf_pdf_dpdf`) so we can keep the existing API stable.
    let two = V::splat(2.0);
    let three_halves = V::splat(1.5);
    let inv_x = V::splat(1.0) / x;
    let inv_x2 = inv_x * inv_x;
    let inv_x3 = inv_x2 * inv_x;
    let l = V::splat(0.5) * inv_x2 - three_halves * inv_x - V::splat(1.0) / (two * mu * mu);
    let l_prime = -inv_x3 + three_halves * inv_x2;

    let f = pdf;
    let f_p = f * l;
    let f_pp = f * (l * l + l_prime);

    // v inverse powers
    let inv_v = V::splat(1.0) / v;
    let inv_v2 = inv_v * inv_v;
    let inv_v3 = inv_v2 * inv_v;
    let inv_v4 = inv_v2 * inv_v2;
    let inv_v5 = inv_v4 * inv_v;
    let inv_v6 = inv_v4 * inv_v2;
    let inv_v7 = inv_v6 * inv_v;
    let inv_v9 = inv_v6 * inv_v3;

    let g = cdf - q;
    let gp = -V::splat(8.0) * f * inv_v3;
    let gpp = V::splat(64.0) * f_p * inv_v6 + V::splat(24.0) * f * inv_v4;
    let gppp = -V::splat(512.0) * f_pp * inv_v9
        - V::splat(576.0) * f_p * inv_v7
        - V::splat(96.0) * f * inv_v5;

    let gp2 = gp * gp;
    let gp3 = gp2 * gp;
    let g2 = g * g;
    let num = V::splat(6.0) * g * gp2 - V::splat(3.0) * g2 * gpp;
    let den = V::splat(6.0) * gp3 - V::splat(6.0) * g * gp * gpp + g2 * gppp;
    let den_safe = den.abs().simd_max(V::splat(1e-300));
    let signed_den = den.is_sign_negative().select(-den_safe, den_safe);
    v - num / signed_den
}

/// Bivariate Chebyshev seed: `ln(v) ≈ Σ_m Σ_n c_mn · T_m(u(k)) · T_n(w(p))`,
/// lane-packed. Caller clamps `(k, p)` into the seed domain before calling.
#[inline]
fn cheb_seed(k_abs: V, q: V) -> V {
    // Transform: u(k) = (2·ln(k) − [ln(K_LO)+ln(K_HI)]) / [ln(K_HI)−ln(K_LO)].
    let ln_k = norm::vlog(k_abs);
    let u_centre = V::splat(0.5 * (SEED_LN_K_LO + SEED_LN_K_HI));
    let u_half_width = V::splat(0.5 * (SEED_LN_K_HI - SEED_LN_K_LO));
    let u = (ln_k - u_centre) / u_half_width;

    // Transform: w(p) = (2·logit(p) − [logit(P_LO)+logit(P_HI)]) / [logit(P_HI)−logit(P_LO)].
    //   logit(p) = ln(p / (1 - p))   — ~3 ns vs ~35 ns for phi_inv.
    let logit_q = norm::vlog(q / (V::splat(1.0) - q));
    let w_centre = V::splat(0.5 * (SEED_LOGIT_P_LO + SEED_LOGIT_P_HI));
    let w_half_width = V::splat(0.5 * (SEED_LOGIT_P_HI - SEED_LOGIT_P_LO));
    let w = (logit_q - w_centre) / w_half_width;

    // Chebyshev recurrence: T_0(u) = 1, T_1(u) = u, T_n(u) = 2u·T_{n-1} − T_{n-2}.
    let mut tu = [V::splat(0.0); SEED_DEG + 1];
    let mut tw = [V::splat(0.0); SEED_DEG + 1];
    tu[0] = V::splat(1.0);
    tu[1] = u;
    tw[0] = V::splat(1.0);
    tw[1] = w;
    let two_u = V::splat(2.0) * u;
    let two_w = V::splat(2.0) * w;
    let mut i = 2;
    while i <= SEED_DEG {
        tu[i] = two_u * tu[i - 1] - tu[i - 2];
        tw[i] = two_w * tw[i - 1] - tw[i - 2];
        i += 1;
    }

    // Bilinear sum: ln(v) = Σ_m Σ_n c_mn · T_m(u) · T_n(w).
    let mut sum = V::splat(0.0);
    let mut m = 0;
    while m <= SEED_DEG {
        let tm = tu[m];
        let mut n = 0;
        while n <= SEED_DEG {
            sum = sum + V::splat(SEED_COEFFS[m][n]) * tm * tw[n];
            n += 1;
        }
        m += 1;
    }
    norm::vexp(sum)
}

