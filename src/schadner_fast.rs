//! `voltic::schadner_fast` — Schadner IV via Chebyshev seed + one Halley step.
//!
//! The v1.1 "fastest at machine precision" kernel. Same explicit-formula
//! starting point as [`crate::schadner`] (Schadner 2026, arXiv:2604.24480 —
//! the BS call price is the survival function of an inverse Gaussian, so
//! `σ(K, C) = (2/√T)·F_IG⁻¹((1−c)/m; 2/|k|, 1)^(−1/2)`). The IG quantile has
//! no elementary closed form and is itself a root of the IG CDF; this module
//! takes that root by **one Halley step** from a pre-fit Chebyshev seed
//! accurate to ~9e-7 across the canonical domain.
//!
//! ## Why this beats Newton/Halley from CM seed
//!
//! Halley's method is convergence order 3: each step takes residual `e` to
//! `~e³`. The seed quality bounds the achievable precision in N steps:
//!
//! ```text
//!   CM seed       (1%) → Newton (3-4 iters) → conditioning floor
//!   CM seed       (1%) → Halley (2-3 iters) → conditioning floor
//!   Chebyshev seed (1e-7) → Halley (1 iter)   → machine precision
//! ```
//!
//! The Chebyshev seed is the load-bearing piece. It was fit offline (see
//! `tools/fit_seed.py`) by Newton-to-tolerance over a 48×48 Chebyshev node
//! grid in the transformed (ln k, Φ⁻¹ p)-domain, truncated to a 23×23 bivariate
//! Chebyshev expansion of `ln v`. Max absolute seed error on an 80×80 uniform
//! test grid is **8.8e-7** — six orders better than what one Halley needs to
//! land at f64 conditioning floor.
//!
//! ## Halley update derivation
//!
//! Iterate in vol space `v = σ·√T` (better-conditioned than `x = 4/v²`; a
//! tail overshoot in `x` would land at a clamp). Residual:
//!
//! ```text
//!   G(v)   = F_IG(x; μ, 1) − q    with x = 4/v², q = (1 − c)/m, μ = 2/|k|
//!   G'(v)  = −8·f_IG(x)/v³
//!   G''(v) = 64·f'_IG(x)/v⁶ + 24·f_IG(x)/v⁴
//! ```
//!
//! Halley:  `v ← v − 2·G·G' / (2·(G')² − G·G'')`.
//!
//! `f'_IG = f_IG · [μ/(2x²) − 3/(2x) − 1/(2μ²)]` — algebraic, no extra
//! transcendental.
//!
//! ## Clean-room provenance
//!
//! The seed was generated from the published Schadner formula + bracketed
//! Newton against the IG CDF as defined in the paper. No code from
//! [wol-fi/volfi] was read at any point. The 23×23 coefficient table is a
//! direct fit; the implementation is independent.
//!
//! [wol-fi/volfi]: https://github.com/wol-fi/volfi

